class _Tee:
    def __init__(self, path, stdout):
        self.file = open(path, "w", encoding="utf-8")
        self.stdout = stdout

    def write(self, s):
        self.stdout.write(s)
        self.file.write(s)

    def flush(self):
        self.stdout.flush()
        self.file.flush()


@contextmanager
def log_to_file(filename):
    orig = sys.stdout
    tee = _Tee(os.path.join(OUT_DIR, filename), orig)
    sys.stdout = tee
    try:
        yield
    finally:
        sys.stdout = orig
        tee.file.close()


def load_ae_splits():
    """Load the pre-scaled CSVs created by prepare_autoencoder_data.py."""
    required = ["X_train_normal.csv", "X_val.csv", "y_val.csv", "X_test.csv", "y_test.csv"]
    missing = [f for f in required if not os.path.exists(os.path.join(AE_DATA_DIR, f))]
    if missing:
        raise FileNotFoundError(
            f"Missing {missing} in dataset/autoencoder_ready/. "
            "Run `python prepare_autoencoder_data.py` first."
        )

    X_tr_norm = pd.read_csv(os.path.join(AE_DATA_DIR, "X_train_normal.csv")).values.astype(np.float64)
    X_val     = pd.read_csv(os.path.join(AE_DATA_DIR, "X_val.csv")).values.astype(np.float64)
    y_val_df  = pd.read_csv(os.path.join(AE_DATA_DIR, "y_val.csv"))
    X_test    = pd.read_csv(os.path.join(AE_DATA_DIR, "X_test.csv")).values.astype(np.float64)
    y_test_df = pd.read_csv(os.path.join(AE_DATA_DIR, "y_test.csv"))

    print(f"Loaded splits: X_train_normal={X_tr_norm.shape} | X_val={X_val.shape} | X_test={X_test.shape}")
    return X_tr_norm, X_val, y_val_df, X_test, y_test_df


# ═══════════════════════════════════════════════════════════════════════════════
#   Autoencoder (Input -> 32 -> 12 -> 32 -> Output)
# ═══════════════════════════════════════════════════════════════════════════════

class NumpyAutoencoder:
    """ 4-layer symmetric autoencoder"""

    def __init__(self, input_dim, hidden_dim=32, latent_dim=12, seed=42):
        rng = np.random.default_rng(seed)
        dims = [input_dim, hidden_dim, latent_dim, hidden_dim, input_dim]

        # Xavier/Glorot init for smooth tanh activations
        self.W = [
            rng.normal(0.0, np.sqrt(2.0 / (dims[i] + dims[i + 1])), size=(dims[i], dims[i + 1]))
            for i in range(4)
        ]
        self.b = [np.zeros((1, dims[i + 1])) for i in range(4)]

        # Adam moving averages
        self.mW = [np.zeros_like(w) for w in self.W]
        self.vW = [np.zeros_like(w) for w in self.W]
        self.mb = [np.zeros_like(b) for b in self.b]
        self.vb = [np.zeros_like(b) for b in self.b]
        self.t  = 0

    def forward(self, X):
        """Run forward pass and return activations for backprop."""
        a1 = np.tanh(X  @ self.W[0] + self.b[0])   # Encoder hidden
        a2 = np.tanh(a1 @ self.W[1] + self.b[1])   # Bottleneck (latent)
        a3 = np.tanh(a2 @ self.W[2] + self.b[2])   # Decoder hidden
        x_hat = a3 @ self.W[3] + self.b[3]         # Linear output
        return [X, a1, a2, a3, x_hat]

    def reconstruction_error(self, X):
        """Per-row Mean Squared Error between input X and reconstructed output."""
        x_hat = self.forward(X)[-1]
        return np.mean((X - x_hat) ** 2, axis=1)

    def train_step(self, X_batch, lr=1e-3):
        """One mini-batch forward + backprop + Adam update step."""
        n, d = X_batch.shape
        acts = self.forward(X_batch)
        x_hat = acts[-1]

        # Gradient of MSE = mean((x_hat - X)^2) w.r.t. output layer
        delta = (2.0 / (n * d)) * (x_hat - X_batch)

        dW, db = [None] * 4, [None] * 4
        for i in reversed(range(4)):
            dW[i] = np.clip(acts[i].T @ delta, -5.0, 5.0)
            db[i] = np.clip(np.sum(delta, axis=0, keepdims=True), -5.0, 5.0)
            if i > 0:
                # Backprop through tanh: d/dz tanh(z) = 1 - a^2
                delta = (delta @ self.W[i].T) * (1.0 - acts[i] ** 2)

        # Adam parameter update
        self.t += 1
        b1, b2, eps = 0.9, 0.999, 1e-8
        for i in range(4):
            self.mW[i] = b1 * self.mW[i] + (1 - b1) * dW[i]
            self.vW[i] = b2 * self.vW[i] + (1 - b2) * (dW[i] ** 2)
            m_hat = self.mW[i] / (1 - b1 ** self.t)
            v_hat = self.vW[i] / (1 - b2 ** self.t)
            self.W[i] -= lr * m_hat / (np.sqrt(v_hat) + eps)

            self.mb[i] = b1 * self.mb[i] + (1 - b1) * db[i]
            self.vb[i] = b2 * self.vb[i] + (1 - b2) * (db[i] ** 2)
            mb_hat = self.mb[i] / (1 - b1 ** self.t)
            vb_hat = self.vb[i] / (1 - b2 ** self.t)
            self.b[i] -= lr * mb_hat / (np.sqrt(vb_hat) + eps)

        return float(np.mean((X_batch - x_hat) ** 2))

    def get_weights(self):
        return [w.copy() for w in self.W], [b.copy() for b in self.b]

    def set_weights(self, W, b):
        self.W = [w.copy() for w in W]
        self.b = [bi.copy() for bi in b]


def fit_autoencoder(model, X_train_norm, X_val_norm, epochs=40, batch_size=256, lr=1e-3, patience=6):
    """Train on Normal flows with mini-batches and early stopping on val Normal MSE."""
    rng = np.random.default_rng(RANDOM_STATE)
    n = len(X_train_norm)

    best_val = np.inf
    best_weights = model.get_weights()
    wait = 0
    history = {"train_loss": [], "val_loss": []}

    t0 = time.time()
    for ep in range(1, epochs + 1):
        idx = rng.permutation(n)
        batch_losses = []
        for start in range(0, n, batch_size):
            batch_losses.append(model.train_step(X_train_norm[idx[start:start + batch_size]], lr=lr))

        tr_loss = float(np.mean(batch_losses))
        va_loss = float(np.mean(model.reconstruction_error(X_val_norm)))
        history["train_loss"].append(tr_loss)
        history["val_loss"].append(va_loss)

        if ep == 1 or ep % 5 == 0 or ep == epochs:
            print(f"  Epoch {ep:2d}/{epochs} | train_mse={tr_loss:.5f} | val_normal_mse={va_loss:.5f}")

        if va_loss < best_val - 1e-5:
            best_val = va_loss
            best_weights = model.get_weights()
            wait = 0
        else:
            wait += 1
            if wait >= patience:
                print(f"  Early stopping at epoch {ep} (best val_normal_mse={best_val:.5f})")
                break

    model.set_weights(*best_weights)
    print(f"Training finished in {time.time() - t0:.1f}s (best val_normal_mse={best_val:.5f})")
    return history


# ═══════════════════════════════════════════════════════════════════════════════
#  Threshold Tuning, Evaluation & Plotting
# ═══════════════════════════════════════════════════════════════════════════════

def pick_best_threshold(val_err, y_val):
    """Sweep candidate thresholds on validation errors and pick the one with highest F1."""
    candidates = np.quantile(val_err, np.linspace(0.10, 0.99, 250))
    best_th, best_f1 = candidates[0], -1.0
    for th in candidates:
        f1 = f1_score(y_val, (val_err >= th).astype(int))
        if f1 > best_f1:
            best_f1, best_th = f1, th
    return float(best_th)


def evaluate_split(name, err, y_df, threshold):
    """Compute binary metrics, confusion matrix, and per-attack-category recall."""
    y_true = y_df["label"].values
    y_pred = (err >= threshold).astype(int)

    auc  = roc_auc_score(y_true, err)
    f1   = f1_score(y_true, y_pred)
    prec = precision_score(y_true, y_pred, zero_division=0)
    rec  = ((y_true == 1) & (y_pred == 1)).sum() / (y_true == 1).sum()
    far  = ((y_true == 0) & (y_pred == 1)).sum() / (y_true == 0).sum()
    cm   = confusion_matrix(y_true, y_pred)

    print(f"\n── {name} Results (cutoff: error >= {threshold:.5f} => Attack) ──")
    print(f"  ROC-AUC (overall separation) : {auc:.4f}   (0.50=random, 1.00=perfect)")
    print(f"  Binary F1 (precision/recall) : {f1:.4f}")
    print(f"  Precision (alert accuracy)   : {prec:.1%}")
    print(f"  Attack Recall (caught)       : {rec:.1%}   ({cm[1,1]:,} caught / {cm[1,0]:,} missed)")
    print(f"  False Alarm Rate (FAR)       : {far:.1%}   ({cm[0,1]:,} false alerts / {cm[0,0]:,} ok)")

    # Recall breakdown per attack_cat
    cat_rec = {}
    print("  Breakdown by traffic type (% flagged as Attack):")
    for cat, grp in y_df.groupby("attack_cat"):
        idx = grp.index.values
        rate = float((y_pred[idx] == 1).mean())
        cat_rec[cat] = rate
        tag = "<- False Alarm (lower is better)" if cat == "Normal" else "<- Caught (higher is better)"
        print(f"    {cat:16s} (n={len(idx):6,}): {rate:5.1%}  {tag}")
    return cat_rec, cm


def plot_confusion_matrices(val_cm, test_cm):
    """Plot Validation and Official Test confusion matrices side-by-side."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))
    cell_tags = [["TN", "FP"], ["FN", "TP"]]
    labels = ["Normal (0)", "Attack (1)"]

    for ax, cm, title in [(axes[0], val_cm, "Validation Set"), (axes[1], test_cm, "Official Test Set")]:
        row_pct = cm / cm.sum(axis=1, keepdims=True)
        ax.imshow(row_pct, cmap="Blues", vmin=0.0, vmax=1.0)
        ax.set_xticks([0, 1])
        ax.set_yticks([0, 1])
        ax.set_xticklabels(labels)
        ax.set_yticklabels(labels)
        ax.set_xlabel("Predicted")
        ax.set_ylabel("Actual")
        ax.set_title(title)

        for i in range(2):
            for j in range(2):
                color = "white" if row_pct[i, j] > 0.55 else "black"
                ax.text(
                    j, i,
                    f"{cell_tags[i][j]}\n{cm[i, j]:,}\n({row_pct[i, j]:.1%})",
                    ha="center", va="center", color=color, fontsize=11, fontweight="bold",
                )

    fig.suptitle("Autoencoder Confusion Matrices (Counts & Row %)", fontsize=13, fontweight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.94])
    fig.savefig(os.path.join(PLOT_DIR, "ae_confusion_matrix.png"), dpi=120)
    plt.close(fig)
    print("  [plot saved] plots/ae_confusion_matrix.png")


def plot_training_curve(history):
    fig, ax = plt.subplots(figsize=(9, 5))
    ep = np.arange(1, len(history["train_loss"]) + 1)
    ax.plot(ep, history["train_loss"], label="Train Normal MSE", lw=2, color="#2b6cb0")
    ax.plot(ep, history["val_loss"],   label="Val Normal MSE (unseen)", lw=2, color="#dd6b20", ls="--")
    ax.set_xlabel("Epoch (full passes through Normal train data)")
    ax.set_ylabel("Reconstruction Error (MSE — lower is better)")
    ax.set_title("Autoencoder Learning Curve (Normal Traffic Only)")
    ax.legend()
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "ae_training_curve.png"), dpi=120)
    plt.close(fig)
    print("  [plot saved] plots/ae_training_curve.png")


def plot_error_and_eval(test_err, y_test_df, threshold, test_cat_rec):
    fig, axes = plt.subplots(1, 2, figsize=(16, 6))

    # Left: log10 reconstruction error distribution (Normal vs Attack on test)
    norm_e = np.log10(test_err[y_test_df["label"] == 0] + 1e-8)
    att_e  = np.log10(test_err[y_test_df["label"] == 1] + 1e-8)
    th_log = np.log10(threshold + 1e-8)
    axes[0].hist(norm_e, bins=70, alpha=0.65, density=True, label="Normal traffic", color="#2b6cb0")
    axes[0].hist(att_e,  bins=70, alpha=0.65, density=True, label="Attack traffic", color="#e53e3e")
    axes[0].axvline(th_log, color="black", ls="--", lw=2, label=f"Cutoff ({threshold:.4f})")
    axes[0].text(th_log - 0.08, axes[0].get_ylim()[1] * 0.90, "← Predicted Normal", ha="right", fontsize=8, fontweight="bold")
    axes[0].text(th_log + 0.08, axes[0].get_ylim()[1] * 0.90, "Predicted Attack →", ha="left",  fontsize=8, fontweight="bold")
    axes[0].set_xlabel("log10(Reconstruction Error)  [right = harder to rebuild]")
    axes[0].set_ylabel("Density")
    axes[0].set_title("How Well Normal & Attack Errors Separate (Test Set)")
    axes[0].legend(loc="upper left")

    # Right: per-class detection rate on test
    cats = sorted(test_cat_rec.keys(), key=lambda k: test_cat_rec[k])
    vals = [test_cat_rec[k] for k in cats]
    cols = ["#718096" if k == "Normal" else "#dd6b20" for k in cats]
    axes[1].barh(cats, vals, color=cols)
    axes[1].set_xlim(0, 1.12)
    axes[1].set_xlabel("Share Flagged as Attack")
    axes[1].set_title("Detection Rate per Category (orange=caught, grey=false alarm)")
    for i, v in enumerate(vals):
        axes[1].text(v + 0.015, i, f"{v:.1%}", va="center", fontsize=8)

    fig.suptitle("Autoencoder Evaluation (Official Test Set)", fontsize=13, fontweight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    fig.savefig(os.path.join(PLOT_DIR, "ae_error_and_eval.png"), dpi=120)
    plt.close(fig)
    print("  [plot saved] plots/ae_error_and_eval.png")


# ═══════════════════════════════════════════════════════════════════════════════
#  Main Entry Point
# ═══════════════════════════════════════════════════════════════════════════════

def main():
    with log_to_file("ae_model_log.txt"):
        print("=" * 80)
        print("AUTOENCODER — TRAINING & EVALUATION")
        print("=" * 80)

        X_tr_norm, X_val, y_val_df, X_test, y_test_df = load_ae_splits()
        X_val_norm = X_val[y_val_df["label"].values == 0]

        input_dim = X_tr_norm.shape[1]
        print(f"\nArchitecture: {input_dim} -> {HIDDEN_DIM} -> {LATENT_DIM} -> {HIDDEN_DIM} -> {input_dim} (tanh + linear)")
        model = NumpyAutoencoder(input_dim, hidden_dim=HIDDEN_DIM, latent_dim=LATENT_DIM, seed=RANDOM_STATE)

        print("\nTraining on Normal traffic only:")
        history = fit_autoencoder(
            model, X_tr_norm, X_val_norm,
            epochs=EPOCHS, batch_size=BATCH_SIZE, lr=LR, patience=PATIENCE,
        )

        # Tune threshold on validation, then evaluate on val and official test
        val_err   = model.reconstruction_error(X_val)
        test_err  = model.reconstruction_error(X_test)
        threshold = pick_best_threshold(val_err, y_val_df["label"].values)

        _, val_cm = evaluate_split("Validation", val_err, y_val_df, threshold)
        test_cat_rec, test_cm = evaluate_split("Official Test", test_err, y_test_df, threshold)

        # Save weights + threshold and diagnostic plots
        np.savez(
            os.path.join(OUT_DIR, "ae_weights.npz"),
            W0=model.W[0], W1=model.W[1], W2=model.W[2], W3=model.W[3],
            b0=model.b[0], b1=model.b[1], b2=model.b[2], b3=model.b[3],
            threshold=np.array([threshold]),
        )
        print("\n  [saved] outputs/ae_weights.npz")
        plot_training_curve(history)
        plot_error_and_eval(test_err, y_test_df, threshold, test_cat_rec)
        plot_confusion_matrices(val_cm, test_cm)


if __name__ == "__main__":
    main()
